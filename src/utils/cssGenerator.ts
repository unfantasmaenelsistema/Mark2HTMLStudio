import { DocumentConfig, FontOption } from '../types';

export function getFontFamilyCss(font: FontOption): string {
  switch (font) {
    case 'plus-jakarta':
      return "'Plus Jakarta Sans', system-ui, -apple-system, sans-serif";
    case 'outfit':
      return "'Outfit', system-ui, -apple-system, sans-serif";
    case 'lora':
      return "'Lora', Georgia, 'Times New Roman', serif";
    case 'jetbrains-mono':
      return "'JetBrains Mono', 'Fira Code', monospace";
    case 'system':
    default:
      return "system-ui, -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif";
  }
}

